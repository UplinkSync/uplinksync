#!/usr/bin/env python3
"""Build the three branded WordPress outage drop-ins from one template.

    python3 tools/outage-pages/build.py          # (re)write the three files
    python3 tools/outage-pages/build.py --check  # exit 1 if a committed file differs

Outputs (WordPress loads each one by name, never this script):
    wp-content/php-error.php    fatal PHP error   -> 500   (WP_Fatal_Error_Handler::display_error_template)
    wp-content/maintenance.php  .maintenance on   -> 503 + Retry-After: 600   (wp_maintenance in load.php)
    wp-content/db-error.php     database down     -> 500   (dead_db in functions.php)

Each output is self-contained: no include, no WordPress function, no external request.
The logo is derived from the theme's own SVG (navy background removed, fills mapped to
palette values, coordinates rounded) so the brand mark has one source of truth.
Edit template.html or VARIANTS here, run the build, commit all of it together.
"""
import html
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LOGO_SRC = os.path.join(ROOT, "wp-content/themes/uplinksync-child/assets/images/uplinksync-logo.svg")
TEMPLATE = os.path.join(HERE, "template.html")

VARIANTS = {
    "php-error.php": {
        "why": "a fatal PHP error (WP_Fatal_Error_Handler::display_error_template)",
        "status": (500, "Internal Server Error"),
        "retry": 0,
        "TITLE": "Temporarily down | UplinkSync",
        "STATUS": "Uplink lost. Holding position.",
        "HEADLINE": "We’ve lost the uplink for a moment.",
        "BODY": "Something on our side of the website tripped, so it’s offline for now. "
                "We already know, and we’re on it. Like any good drone, we’re holding "
                "position until the signal is back. Check again in a few minutes.",
    },
    "maintenance.php": {
        "why": "maintenance mode during updates (wp_maintenance)",
        "status": (503, "Service Unavailable"),
        "retry": 600,
        "TITLE": "Updating the site | UplinkSync",
        "STATUS": "Holding pattern. Updates installing.",
        "HEADLINE": "Holding pattern while we update.",
        "BODY": "We’re installing updates, so the site is offline for about ten minutes. "
                "It comes back on its own, and there’s nothing you need to do. "
                "Grab a coffee; we’ll be cleared to land shortly.",
    },
    "db-error.php": {
        "why": "a database connection failure (dead_db)",
        "status": (500, "Internal Server Error"),
        "retry": 0,
        "TITLE": "Temporarily down | UplinkSync",
        "STATUS": "Grounded. Reconnecting.",
        "HEADLINE": "Grounded for a moment.",
        "BODY": "The website can’t reach the place it keeps its pages, so there’s "
                "nothing to show right now. We know, and we’re reconnecting it now. "
                "Check again in a few minutes.",
    },
}

# Theme logo fills -> nearest palette value (tools/ci/lint_palette_hex.py PALETTE).
LOGO_FILLS = {
    "#FAFAFB": "#fbfbfb", "#F4F5F8": "#fbfbfb", "#599BF7": "#579af6", "#5697F3": "#579af6",
    "#72AEFB": "#7db3ff", "#95D5DD": "#93d1e8", "#A7CBF3": "#a4caff", "#D3E3F7": "#e2eeff",
    "#173258": "#173258",
}

PHP_HEAD = """<?php
/**
 * UplinkSync branded outage page: {why}.
 *
 * GENERATED by tools/outage-pages/build.py from tools/outage-pages/template.html.
 * Do not edit by hand; edit the template and rebuild.
 *
 * WordPress may run this very early: assume no WordPress function exists.
 * It always sends an error status ({code}), no-cache and noindex, shows no error
 * detail, and requests nothing (all CSS and SVG inline, system fonts).
 */
if ( ! defined( 'ABSPATH' ) ) {{
	// Requested directly as a URL, not loaded by WordPress: show nothing.
	if ( ! headers_sent() ) {{
		header( 'HTTP/1.1 404 Not Found', true, 404 );
		header( 'X-Robots-Tag: noindex, nofollow' );
	}}
	exit;
}}
if ( ! headers_sent() ) {{
	// Drop any half-rendered page still sitting in output buffers so only this page shows.
	try {{
		for ( $uls_level = ob_get_level(); $uls_level > 0; $uls_level-- ) {{
			if ( ! @ob_end_clean() ) {{
				break;
			}}
		}}
	}} catch ( \\Throwable $uls_e ) {{
		// Keep going: the page below matters more than a stubborn buffer.
	}}
	$uls_protocol = ( isset( $_SERVER['SERVER_PROTOCOL'] ) && is_string( $_SERVER['SERVER_PROTOCOL'] )
		&& preg_match( '#^HTTP/[0-9](\\.[0-9])?$#', $_SERVER['SERVER_PROTOCOL'] ) ) ? $_SERVER['SERVER_PROTOCOL'] : 'HTTP/1.1';
	header( $uls_protocol . ' {code} {reason}', true, {code} );
	header( 'Content-Type: text/html; charset=utf-8' );
	header( 'Cache-Control: no-cache, no-store, must-revalidate, max-age=0' );
	header( 'Pragma: no-cache' );
	header( 'Expires: Wed, 11 Jan 1984 05:00:00 GMT' );
	header( 'X-Robots-Tag: noindex, nofollow' );
	header( 'X-LiteSpeed-Cache-Control: no-cache' );{retry}
	if ( function_exists( 'header_remove' ) ) {{
		header_remove( 'Last-Modified' );
	}}
}}
?>
"""


def logo_paths():
    src = open(LOGO_SRC, encoding="utf-8").read()
    groups = {}
    for i, m in enumerate(re.finditer(r'<path fill="(#[0-9A-Fa-f]+)"[^>]*?d="([^"]+)"', src)):
        if i == 0:  # the navy square background; the sky panel supplies it
            continue
        fill, d = m.groups()
        d = re.sub(r"-?\d+(?:\.\d+)?", lambda n: str(int(round(float(n.group(0))))), d)
        d = re.sub(r"\s+", " ", d).strip()
        d = re.sub(r" ?([MCLZ]) ?", r"\1", d)
        d = re.sub(r" ?, ?", ",", d)
        d = d.replace(",-", "-").replace(" -", "-")
        groups.setdefault(LOGO_FILLS[fill.upper()], []).append(d)
    return "".join(f'<path fill="{f}" d="{"".join(ds)}"/>' for f, ds in groups.items())


def render(name, v, logo, template):
    code, reason = v["status"]
    retry = f"\n\theader( 'Retry-After: {v['retry']}' );" if v["retry"] else ""
    head = PHP_HEAD.format(why=v["why"], code=code, reason=reason, retry=retry)
    page = template.replace("{{LOGO}}", logo)
    for key in ("TITLE", "STATUS", "HEADLINE", "BODY"):
        page = page.replace("{{%s}}" % key, html.escape(v[key], quote=False))
    if "{{" in page or "<?" in page:
        raise SystemExit(f"{name}: unresolved placeholder or stray PHP open tag in page body")
    return head + page


def main(argv):
    check = "--check" in argv
    template = open(TEMPLATE, encoding="utf-8").read()
    logo = logo_paths()
    bad = 0
    for name, v in VARIANTS.items():
        out = render(name, v, logo, template)
        path = os.path.join(ROOT, "wp-content", name)
        if check:
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != out:
                print(f"STALE: wp-content/{name} differs from the template; run build.py")
                bad = 1
            else:
                print(f"OK: wp-content/{name} ({len(out.encode())} bytes)")
        else:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(out)
            print(f"wrote wp-content/{name} ({len(out.encode())} bytes)")
    sys.exit(bad)


if __name__ == "__main__":
    main(sys.argv)
